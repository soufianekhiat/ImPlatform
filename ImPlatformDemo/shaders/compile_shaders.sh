#!/bin/sh
# Compiles every *.hlsl here (entry points vs_main and ps_main) for each graphics backend into the headers main.cpp
# includes (generated, committed):
#   <name>.hlsl.h  the HLSL source, compiled at run time by Direct3D 10, 11 and 12
#   <name>.spv.h   SPIR-V for Vulkan (Slang)
#   <name>.glsl.h  GLSL 330 for OpenGL (Slang's SPIR-V converted by SPIRV-Cross)
#   <name>.wgsl.h  WGSL for WebGPU (Slang)
# Needs curl (to fetch Slang, see buildsystem/fetch_slang.sh) and spirv-cross (Vulkan SDK or the spirv-cross package).
# Windows: compile_shaders.bat. Both scripts must produce the same output.
set -e
cd "$(dirname "$0")"

SLANGC=$(sh ../../buildsystem/fetch_slang.sh)
SPIRV_CROSS=spirv-cross
for dir in "$VULKAN_SDK/bin" "$VULKAN_SDK/Bin"; do
    if [ -n "$VULKAN_SDK" ] && [ -x "$dir/spirv-cross" ]; then SPIRV_CROSS="$dir/spirv-cross"; fi
done
if ! command -v "$SPIRV_CROSS" >/dev/null 2>&1; then
    echo "Error: spirv-cross not found (Vulkan SDK, or the spirv-cross package)" >&2
    exit 1
fi

# Each register class in its own binding range (t 0-15, s 16-31, b 32-47, u 48+): the Vulkan backend moves them to
# Dear ImGui's descriptor sets. OpenGL and WebGPU take GL_SHIFTS: b0 -> 0, b1 -> 1, t0 -> 16, s0 -> 32.
VK_SHIFTS="-fvk-t-shift 0 0 -fvk-s-shift 16 0 -fvk-b-shift 32 0 -fvk-u-shift 48 0"
GL_SHIFTS="-fvk-b-shift 0 0 -fvk-t-shift 16 0 -fvk-s-shift 32 0 -fvk-u-shift 48 0"
# GLSL 330 links vertex outputs to fragment inputs by name: both sides are named after their location.
RENAME_OUT=""
RENAME_IN=""
for loc in 0 1 2 3 4 5 6 7; do
    RENAME_OUT="$RENAME_OUT --rename-interface-variable out $loc vary$loc"
    RENAME_IN="$RENAME_IN --rename-interface-variable in $loc vary$loc"
done

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# SPIR-V as a C array of little-endian 32-bit words, 8 per line
words() {
    od -An -tx4 -v "$1" | awk '{ for (i = 1; i <= NF; i++) w[n++] = "0x" $i }
        END { for (i = 0; i < n; i++) printf "%s%s%s", (i % 8 == 0 ? "    " : " "), w[i], (i == n - 1 ? "\n" : (i % 8 == 7 ? ",\n" : ",")) }'
}
# Text as a C string literal, one quoted line per source line
cstring() {
    sed 's/\r$//; s/\\/\\\\/g; s/"/\\"/g; s/^/    "/; s/$/\\n"/' "$1"
}

for src in *.hlsl; do
    name=${src%.hlsl}
    for stage in vs ps; do
        if [ $stage = vs ]; then kind=vertex; rename=$RENAME_OUT; else kind=fragment; rename=$RENAME_IN; fi
        "$SLANGC" "$src" -entry ${stage}_main -stage $kind -target spirv -profile spirv_1_3 -O3 $VK_SHIFTS -o "$TMP/$stage.spv"
        "$SLANGC" "$src" -entry ${stage}_main -stage $kind -target spirv -profile spirv_1_3 -O3 $GL_SHIFTS -o "$TMP/$stage.gl.spv"
        "$SPIRV_CROSS" "$TMP/$stage.gl.spv" --version 330 --no-es $rename --output "$TMP/$stage.glsl"
        "$SLANGC" "$src" -entry ${stage}_main -stage $kind -target wgsl $GL_SHIFTS -o "$TMP/$stage.wgsl"
    done

    banner="// Generated by compile_shaders from $src: do not edit."
    { echo "$banner"; echo "static const char ${name}_hlsl[] ="; cstring "$src"; echo "    ;"; } > "$name.hlsl.h"
    {
        echo "$banner"
        echo "static const unsigned int ${name}_vs_spv[] = {"; words "$TMP/vs.spv"; echo "};"
        echo "static const unsigned int ${name}_ps_spv[] = {"; words "$TMP/ps.spv"; echo "};"
    } > "$name.spv.h"
    {
        echo "$banner"
        echo "static const char ${name}_vs_glsl[] ="; cstring "$TMP/vs.glsl"; echo "    ;"
        echo "static const char ${name}_ps_glsl[] ="; cstring "$TMP/ps.glsl"; echo "    ;"
    } > "$name.glsl.h"
    {
        echo "$banner"
        echo "static const char ${name}_vs_wgsl[] ="; cstring "$TMP/vs.wgsl"; echo "    ;"
        echo "static const char ${name}_ps_wgsl[] ="; cstring "$TMP/ps.wgsl"; echo "    ;"
    } > "$name.wgsl.h"
    echo "$src -> $name.hlsl.h $name.spv.h $name.glsl.h $name.wgsl.h"
done
