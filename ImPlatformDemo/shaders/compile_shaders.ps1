# Windows version of compile_shaders.sh, run by compile_shaders.bat; both scripts must produce the same output.
# Compiles every *.hlsl here (entry points vs_main and ps_main, or cs_main for a compute shader) for each graphics backend
# into the headers main.cpp includes (generated, committed):
#   <name>.hlsl.h  the HLSL source, compiled at run time by Direct3D 9 (vs_3_0 / ps_3_0), 10, 11 and 12
#   <name>.spv.h   SPIR-V for Vulkan (Slang)
#   <name>.glsl.h  GLSL 330 for OpenGL (Slang's SPIR-V converted by SPIRV-Cross)
#   <name>.wgsl.h  WGSL for WebGPU (Slang)
#   <name>.metal.h MSL for Metal (Slang), buffer indices shifted by one: Dear ImGui's vertices are at buffer 0
# A compute shader gets <name>.hlsl.h, <name>.spv.h and <name>.glsl.h (GLSL 430) with ImPlatform_DispatchCompute's bindings.
# Needs spirv-cross (Vulkan SDK); Slang is fetched by buildsystem\fetch_slang.bat.
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$slangc = cmd /c "`"$PSScriptRoot\..\..\buildsystem\fetch_slang.bat`"" | Select-Object -Last 1
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $slangc)) { throw 'fetch_slang.bat failed' }
$spirvCross = if ($env:VULKAN_SDK -and (Test-Path "$env:VULKAN_SDK\Bin\spirv-cross.exe")) { "$env:VULKAN_SDK\Bin\spirv-cross.exe" }
              else { (Get-Command spirv-cross -ErrorAction SilentlyContinue).Source }
if (-not $spirvCross) { throw 'spirv-cross not found (Vulkan SDK)' }

# Each register class in its own binding range (t 0-15, s 16-31, b 32-47, u 48+): the Vulkan backend moves them to
# Dear ImGui's descriptor sets. OpenGL and WebGPU take $glShifts: b0 -> 0, b1 -> 1, t0 -> 16, s0 -> 32.
$vkShifts = '-fvk-t-shift', '0', '0', '-fvk-s-shift', '16', '0', '-fvk-b-shift', '32', '0', '-fvk-u-shift', '48', '0'
$glShifts = '-fvk-b-shift', '0', '0', '-fvk-t-shift', '16', '0', '-fvk-s-shift', '32', '0', '-fvk-u-shift', '48', '0'
# GLSL 330 links vertex outputs to fragment inputs by name: both sides are named after their location.
$renameOut = @(); $renameIn = @()
foreach ($loc in 0..7) {
    $renameOut += '--rename-interface-variable', 'out', "$loc", "vary$loc"
    $renameIn  += '--rename-interface-variable', 'in',  "$loc", "vary$loc"
}

$tmp = Join-Path ([IO.Path]::GetTempPath()) ([IO.Path]::GetRandomFileName())
New-Item -ItemType Directory $tmp | Out-Null

function Invoke-Tool([string]$exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe failed" }
}
# SPIR-V as a C array of little-endian 32-bit words, 8 per line
function Format-Words([string]$path) {
    $bytes = [IO.File]::ReadAllBytes($path)
    $words = for ($i = 0; $i -lt $bytes.Length; $i += 4) { '0x{0:x8}' -f [BitConverter]::ToUInt32($bytes, $i) }
    $lines = for ($i = 0; $i -lt $words.Count; $i += 8) {
        $last = [Math]::Min($i + 7, $words.Count - 1)
        '    ' + ($words[$i..$last] -join ', ') + $(if ($last -lt $words.Count - 1) { ',' } else { '' })
    }
    $lines -join "`n"
}
# Text as a C string literal, one quoted line per source line
function Format-CString([string]$path) {
    (Get-Content -LiteralPath $path | ForEach-Object { '    "' + ($_ -replace '\\', '\\' -replace '"', '\"') + '\n"' }) -join "`n"
}
function Write-Header([string]$path, [string[]]$parts) {
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot $path), (($parts -join "`n") + "`n"))
}

try {
    foreach ($src in Get-ChildItem *.hlsl | Sort-Object Name) {
        $name = $src.BaseName
        $banner = "// Generated by compile_shaders from $($src.Name): do not edit."
        if (Select-String -Quiet -LiteralPath $src.FullName -Pattern '\bcs_main\b') {
            # ImPlatform_DispatchCompute's bindings. Vulkan: constants 0, inputs 1.., outputs 9.. OpenGL: each class from 0.
            $common = @($src.Name, '-entry', 'cs_main', '-stage', 'compute', '-target', 'spirv', '-profile', 'spirv_1_3', '-O3')
            Invoke-Tool $slangc ($common + @('-fvk-b-shift', '0', '0', '-fvk-t-shift', '1', '0', '-fvk-u-shift', '9', '0', '-o', "$tmp\cs.spv"))
            Invoke-Tool $slangc ($common + @('-fvk-b-shift', '0', '0', '-fvk-t-shift', '0', '0', '-fvk-u-shift', '0', '0', '-o', "$tmp\cs.gl.spv"))
            Invoke-Tool $spirvCross @("$tmp\cs.gl.spv", '--version', '430', '--no-es', '--combined-samplers-inherit-bindings', '--output', "$tmp\cs.glsl")
            Write-Header "$name.hlsl.h" @($banner, "static const char ${name}_hlsl[] =", (Format-CString $src.FullName), '    ;')
            Write-Header "$name.spv.h" @($banner, "static const unsigned int ${name}_cs_spv[] = {", (Format-Words "$tmp\cs.spv"), '};')
            Write-Header "$name.glsl.h" @($banner, "static const char ${name}_cs_glsl[] =", (Format-CString "$tmp\cs.glsl"), '    ;')
            "$($src.Name) -> $name.hlsl.h $name.spv.h $name.glsl.h"
            continue
        }
        foreach ($stage in 'vs', 'ps') {
            $kind = if ($stage -eq 'vs') { 'vertex' } else { 'fragment' }
            $rename = if ($stage -eq 'vs') { $renameOut } else { $renameIn }
            $common = @($src.Name, '-entry', "${stage}_main", '-stage', $kind, '-target', 'spirv', '-profile', 'spirv_1_3', '-O3')
            Invoke-Tool $slangc ($common + $vkShifts + @('-o', "$tmp\$stage.spv"))
            Invoke-Tool $slangc ($common + $glShifts + @('-o', "$tmp\$stage.gl.spv"))
            Invoke-Tool $spirvCross (@("$tmp\$stage.gl.spv", '--version', '330', '--no-es') + $rename + @('--output', "$tmp\$stage.glsl"))
            Invoke-Tool $slangc (@($src.Name, '-entry', "${stage}_main", '-stage', $kind, '-target', 'wgsl') + $glShifts + @('-o', "$tmp\$stage.wgsl"))
            # 39001: Slang reports s0 overlapping b0, which are separate argument tables in Metal.
            Invoke-Tool $slangc @($src.Name, '-entry', "${stage}_main", '-stage', $kind, '-target', 'metal', '-line-directive-mode', 'none', '-warnings-disable', '39029,39001', '-o', "$tmp\$stage.metal")
            $msl = [regex]::Replace([IO.File]::ReadAllText("$tmp\$stage.metal"), '\[\[buffer\((\d+)\)\]\]', { param($m) "[[buffer($([int]$m.Groups[1].Value + 1))]]" })
            [IO.File]::WriteAllText("$tmp\$stage.metal", $msl)
        }

        Write-Header "$name.hlsl.h" @($banner, "static const char ${name}_hlsl[] =", (Format-CString $src.FullName), '    ;')
        Write-Header "$name.spv.h" @($banner,
            "static const unsigned int ${name}_vs_spv[] = {", (Format-Words "$tmp\vs.spv"), '};',
            "static const unsigned int ${name}_ps_spv[] = {", (Format-Words "$tmp\ps.spv"), '};')
        Write-Header "$name.glsl.h" @($banner,
            "static const char ${name}_vs_glsl[] =", (Format-CString "$tmp\vs.glsl"), '    ;',
            "static const char ${name}_ps_glsl[] =", (Format-CString "$tmp\ps.glsl"), '    ;')
        Write-Header "$name.wgsl.h" @($banner,
            "static const char ${name}_vs_wgsl[] =", (Format-CString "$tmp\vs.wgsl"), '    ;',
            "static const char ${name}_ps_wgsl[] =", (Format-CString "$tmp\ps.wgsl"), '    ;')
        Write-Header "$name.metal.h" @($banner,
            "static const char ${name}_vs_metal[] =", (Format-CString "$tmp\vs.metal"), '    ;',
            "static const char ${name}_ps_metal[] =", (Format-CString "$tmp\ps.metal"), '    ;')
        "$($src.Name) -> $name.hlsl.h $name.spv.h $name.glsl.h $name.wgsl.h $name.metal.h"
    }
}
finally {
    Remove-Item -Recurse -Force $tmp
}
